from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import matplotlib.pyplot as plt
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from reliacircuit.pipeline import PipelineConfig, run_replicate
from reliacircuit.synthetic import SyntheticConfig


def main() -> None:
    args = parse_args()
    config = load_config(args.config)
    if args.replicates is not None:
        config["replicates"] = args.replicates
    output_dir = ROOT / config["output_dir"]
    output_dir.mkdir(parents=True, exist_ok=True)

    synthetic = SyntheticConfig(**config["synthetic"])
    pipeline = PipelineConfig(synthetic=synthetic, **config["pipeline"])

    feature_frames = []
    summary_frames = []
    circuit_frames = []
    for rep in range(int(config["replicates"])):
        features, summary, circuit = run_replicate(pipeline, replicate=rep)
        feature_frames.append(features)
        summary_frames.append(summary)
        circuit_frames.append(circuit)
        print(f"replicate {rep + 1}/{config['replicates']} complete", flush=True)

    feature_table = pd.concat(feature_frames, ignore_index=True)
    summary_table = pd.concat(summary_frames, ignore_index=True)
    circuit_table = pd.concat(circuit_frames, ignore_index=True)
    aggregate = aggregate_summary(summary_table)
    circuit_aggregate = aggregate_circuit_summary(circuit_table)

    feature_table.to_csv(output_dir / "per_feature.csv", index=False)
    summary_table.to_csv(output_dir / "replicate_summary.csv", index=False)
    circuit_table.to_csv(output_dir / "circuit_summary.csv", index=False)
    aggregate.to_csv(output_dir / "aggregate_metrics.csv", index=False)
    circuit_aggregate.to_csv(output_dir / "circuit_aggregate_metrics.csv", index=False)
    write_markdown_report(output_dir / "gate_b_report.md", aggregate, circuit_aggregate, config)
    plot_metrics(aggregate, output_dir / "gate_b_metrics.png")

    print("\nAggregate metrics:")
    print(aggregate.to_string(index=False))
    print("\nCircuit aggregate metrics:")
    print(circuit_aggregate.to_string(index=False))


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", type=Path, default=ROOT / "configs" / "synthetic_gate_b.json")
    parser.add_argument("--replicates", type=int, default=None)
    return parser.parse_args()


def load_config(path: Path) -> dict:
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


def aggregate_summary(summary: pd.DataFrame) -> pd.DataFrame:
    rows = []
    metric_cols = [
        "discoveries",
        "false_discoveries",
        "true_discoveries",
        "fdp",
        "power",
        "ci_coverage_selected",
        "screen_recall",
        "ci_coverage_screened",
    ]
    for method, group in summary.groupby("method", sort=False):
        row = {"method": method, "replicates": int(group.shape[0])}
        for col in metric_cols:
            values = group[col].dropna()
            row[f"{col}_mean"] = float(values.mean()) if not values.empty else float("nan")
            row[f"{col}_se"] = float(values.std(ddof=1) / (values.shape[0] ** 0.5)) if values.shape[0] > 1 else 0.0
        rows.append(row)
    return pd.DataFrame(rows)


def aggregate_circuit_summary(circuit: pd.DataFrame) -> pd.DataFrame:
    rows = []
    metric_cols = [
        "completeness_r2",
        "necessity_fraction",
        "abs_effect_fraction",
        "selected_full_corr",
        "sign_agreement",
    ]
    for method, group in circuit.groupby("method", sort=False):
        row = {"method": method, "replicates": int(group.shape[0])}
        for col in metric_cols:
            values = group[col].dropna()
            row[f"{col}_mean"] = float(values.mean()) if not values.empty else float("nan")
            row[f"{col}_se"] = float(values.std(ddof=1) / (values.shape[0] ** 0.5)) if values.shape[0] > 1 else 0.0
        rows.append(row)
    return pd.DataFrame(rows)


def write_markdown_report(
    path: Path,
    aggregate: pd.DataFrame,
    circuit_aggregate: pd.DataFrame,
    config: dict,
) -> None:
    lines = [
        "# Gate B Synthetic Validation Report",
        "",
        "This report is generated by `scripts/run_synthetic_gate_b.py`.",
        "",
        "## Configuration",
        "",
        "```json",
        json.dumps(config, indent=2),
        "```",
        "",
        "## Aggregate metrics",
        "",
        aggregate.to_markdown(index=False),
        "",
        "## Held-out circuit metrics",
        "",
        circuit_aggregate.to_markdown(index=False),
        "",
        "Gate B criterion for the main method: `e_bh_pcal` should have mean FDP <= q",
        "with non-trivial power, calibrated screened-feature CI coverage, and",
        "held-out circuit-level completeness/necessity evidence.",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def plot_metrics(aggregate: pd.DataFrame, path: Path) -> None:
    fig, axes = plt.subplots(1, 3, figsize=(12, 3.5), constrained_layout=True)
    specs = [
        ("fdp_mean", "fdp_se", "FDP"),
        ("power_mean", "power_se", "Power"),
        ("ci_coverage_screened_mean", "ci_coverage_screened_se", "CI coverage"),
    ]
    for ax, (mean_col, se_col, title) in zip(axes, specs):
        ax.bar(aggregate["method"], aggregate[mean_col], yerr=aggregate[se_col], capsize=3)
        ax.set_title(title)
        ax.tick_params(axis="x", rotation=35)
        ax.set_ylim(0.0, max(1.0, float(aggregate[mean_col].max()) + 0.1))
    fig.savefig(path, dpi=180)
    plt.close(fig)


if __name__ == "__main__":
    main()
